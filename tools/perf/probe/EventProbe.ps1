Write-Output ('EventProbe label={0} probe_pid={1} measured={2}s interval={3}ms' -f $Label, $PID, (Round3 $durationS), [int]$result.IntervalMs)
Write-Output ('Events: {0} total, {1}/s (median {2}/s, max {3}/s)' -f $total, (Round3 $eventsPerS), (Round3 $eventRateMedian), (Round3 $eventRateMax))
Write-Output 'Per type:'
Write-Output $byTypeLine.TrimEnd()
Write-Output ('idObject == 0 : {0} ({1}% ) ; idObject != 0 : {2} ({3}%)' -f $idObjZero, (Round2 $idObjZeroPct), $idObjNonZero, (Round2 $idObjNonZeroPct))
Write-Output ('Would call Check() (type != LOCATIONCHANGE AND idObject == 0): {0} ({1}/s, {2}% of total, {3}% of idObject==0)' -f $check, (Round3 ($check / $durationS)), (Round3 $checkPctOfTotal), (Round3 $checkPctOfIdObjZero))
Write-Output ('LOCATIONCHANGE: {0} total ({1}%), of which idObject==0: {2}' -f $locChange, (Round2 $locChangePct), $locChangeZero)
if ([long]$result.ExcludedEvents -gt 0) {
    Write-Output ('Excluded events (ExcludePid): {0}' -f [long]$result.ExcludedEvents)
}
Write-Output ('Counters consistency: type_sum={0} idobject_sum={1} check_partition={2}' -f $typeSumOk, $idObjectSumOk, $checkPartitionOk)
Write-Output ('Probe self CPU (GROSS, target <0.5% of one core): {0}s over {1}s = {2}% ; control pump {3}s over {4}s = {5}%' -f (Round6 $selfCpuS), (Round3 $durationS), (Round3 $probeCpuPct), (Round6 $controlCpuS), (Round3 $controlDurS), (Round3 $controlCpuPct))
