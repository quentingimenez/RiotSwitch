    meta = [ordered]@{
        tool              = 'tools/perf/probe/EventProbe.ps1'
        version           = '1.2.0'
        label             = $Label
        generated_utc     = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ss.fffZ')
        measured_utc_from = $result.StartedUtc
        measured_utc_to   = $result.EndedUtc
        host              = $env:COMPUTERNAME
        os                = [Environment]::OSVersion.VersionString
        ps_version        = $PSVersionTable.PSVersion.ToString()
        cores_logical     = [Environment]::ProcessorCount
        probe_pid         = $PID
        note              = 'Passive out-of-context hook identical to RiotWindowTracker (range 0x8000-0x800B + 0x0003, WINEVENT_OUTOFCONTEXT|WINEVENT_SKIPOWNPROCESS). Counts only; no Check()/Find()/BeginInvoke.'
    }
    args = [ordered]@{
        duration_s_requested = $DurationSeconds
        duration_s_measured  = Round6 $durationS
        interval_ms          = [int]$result.IntervalMs
        control_s            = Round6 ([double]$result.ControlDurationS)
        warmup_s             = Round6 ([double]$result.WarmupDurationS)
        sampler_pid          = [int]$result.SamplerPid
        exclude_pids         = @($excludeList)
    }
    counters = [ordered]@{
        total_events          = $total
        events_per_s          = Round3 $eventsPerS
        event_rates_per_s     = [ordered]@{
            avg    = Round3 $eventRateAvg
            median = if ($eventRateMedian -ne $null) { Round3 $eventRateMedian } else { $null }
            max    = if ($eventRateMax -ne $null) { Round3 $eventRateMax } else { $null }
        }
        by_type               = $typeRows
        idobject_zero         = $idObjZero
        idobject_zero_per_s   = Round3 ($idObjZero / $durationS)
        idobject_zero_pct     = Round3 $idObjZeroPct
        idobject_nonzero      = $idObjNonZero
        idobject_nonzero_pct  = Round3 $idObjNonZeroPct
        locationchange_total  = $locChange
        locationchange_pct    = Round3 $locChangePct
        locationchange_idobject0 = $locChangeZero
        check_events          = $check
        check_per_s           = Round3 ($check / $durationS)
        check_pct_of_total    = Round3 $checkPctOfTotal
        check_pct_of_idobject0 = Round3 $checkPctOfIdObjZero
        no_check_events       = $noCheckCount
        no_check_pct_of_total = Round3 $noCheckPct
        excluded_events       = [long]$result.ExcludedEvents
        unknown_events        = [long]$result.UnknownEvents
        consistency           = [ordered]@{
            type_sum_equals_total       = $typeSumOk
            idobject_sum_equals_total   = $idObjectSumOk
            check_partition_equals_total = $checkPartitionOk
        }
        hooks = [ordered]@{
            object_hook_ok      = [bool]$result.HookObjectOk
            foreground_hook_ok  = [bool]$result.HookForegroundOk
            object_error        = [int]$result.HookObjectError
            foreground_error    = [int]$result.HookForegroundError
        }
    }
    probe_cost = [ordered]@{
        self_cpu_measure_s       = Round6 $selfCpuS
        self_cpu_control_s       = Round6 $controlCpuS
        control_duration_s       = Round6 $controlDurS
        control_cpu_per_s        = Round6 $controlCpuPerS
        control_cpu_pct_core     = Round3 $controlCpuPct
        self_cpu_pct_core_gross  = Round3 $probeCpuPct
        self_cpu_pct_core_net    = Round3 $probeNetCpuPct
        overhead_target_pct_core = $overheadTargetPct
        overhead_gross_ok        = $overheadGrossOk
        overhead_control_ok      = $overheadControlOk
        overhead_ok              = $overheadOk
        delivery_below_cpu_resolution_ns = $deliveryBelowResolution
        callback_ns_per_call     = if ($callbackNsPerCall -ne $null) { Round3 $callbackNsPerCall } else { $null }
        callback_us_per_call     = if ($callbackUsPerCall -ne $null) { Round6 $callbackUsPerCall } else { $null }
        us_cpu_per_event_including_pump = if ($usPerEventIncl -ne $null) { Round3 $usPerEventIncl } else { $null }
        us_cpu_per_event_net_of_pump    = if ($usPerEventNet -ne $null) { Round3 $usPerEventNet } else { $null }
        method = 'GetProcessTimes(kernel+user) delta over the measurement window (gross) and over the control window (same blocking pump, no hooks). overhead_ok requires BOTH gross < 0.5% and control < 0.5% of one core. callback_ns_per_call is the managed counting callback body measured separately (2e6 direct invocations, 100 ns CPU timer); it is a LOWER BOUND of the app hook cost because the kernel delivery hop and the app BeginInvoke(Check)/Find are excluded.'
    }
    sampler   = $samplerSummary
    correlation = $correlation
}

# ---- CSV series ----
