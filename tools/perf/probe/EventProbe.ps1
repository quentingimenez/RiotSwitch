if ($callbackNsPerCall -ne $null) {
    Write-Output ('Managed counting callback (no Check): {0} ns/call = {1} us/call (lower bound of app hook delivery cost)' -f (Round3 $callbackNsPerCall), (Round6 $callbackUsPerCall))
}
if ($usPerEventIncl -ne $null) {
    if ($deliveryBelowResolution) {
        Write-Output ('Delivery cost: below CPU timer resolution over this window (<100 ns total CPU for {0} events -> <{1} us/event gross)' -f $total, (Round6 (0.1 / $total)))
    }
    else {
        Write-Output ('Delivery cost (gross): {0} us/event incl. pump ; {1} us/event net of pump' -f (Round3 $usPerEventIncl), (Round3 $usPerEventNet))
    }
}
else {
    Write-Output 'Delivery cost: no event received (cannot estimate; run the _EventGen.ps1 positive self-test).'
}
if ($samplerSummary -ne $null) {
    Write-Output ('Sampler pid={0} ({1}): cpu_avg={2}% core, median={3}%, min={4}%, max={5}%, cpu_used={6}s' -f $samplerSummary['pid'], $samplerSummary['process_name'], $samplerSummary['cpu_avg_pct_core'], $samplerSummary['cpu_median_pct_core'], $samplerSummary['cpu_min_pct_core'], $samplerSummary['cpu_max_pct_core'], $samplerSummary['cpu_total_s'])
    if ($correlation -ne $null -and $correlation['r_event_rate_vs_sampler_cpu'] -ne $null) {
        Write-Output ('Correlation r(event_rate, sampler_cpu)={0} ; r lag1={1} on {2} intervals' -f (Round3 $correlation['r_event_rate_vs_sampler_cpu']), (Round3 $correlation['r_event_rate_vs_sampler_cpu_lag1']), $correlation['intervals_used'])
    }
}
else {
    Write-Output 'Sampler: none (no -SamplerPid/-SamplerName).'
}
if ($csvPath -ne '') { Write-Output ('CSV: ' + $csvPath) }
if ($jsonPath -ne '') { Write-Output ('JSON: ' + $jsonPath) }

