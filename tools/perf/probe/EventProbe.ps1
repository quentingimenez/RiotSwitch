$excludeList = @($ExcludePid)
if ($excludeList.Count -gt 0) {
    $options.ExcludePids = [int[]]$excludeList
}

try {
    $result = [RiotSwitchPerf.Probe.WinEventProbe]::Run($options)
}
catch {
    $message = $_.Exception.Message
    Write-Error ("EventProbe failed: " + $message)
    if ($message -match 'SetWinEventHook failed') { exit 2 }
    exit 1
}

# ---- managed callback cost micro-benchmark (after Run(); resets its own counters) ----
# 10e6 direct invocations are needed because Windows process CPU accounting is
# refreshed per clock tick (~15.6 ms on this host).
$callbackNsPerCall = $null
try {
    $callbackNsPerCall = [RiotSwitchPerf.Probe.WinEventProbe]::BenchmarkCallback(10000000)
    if ([double]$callbackNsPerCall -le 0.0) { $callbackNsPerCall = $null }
}
catch {
    $callbackNsPerCall = $null
}

$series = @($result.Series)
$durationS = [double]$result.MeasureDurationS
$total = [long]$result.TotalEvents
if ($durationS -le 0.0) { $durationS = 0.001 }
$eventsPerS = $total / $durationS
$intervalSeconds = [int]$result.IntervalMs / 1000.0

# ---- per-type table (counts and rates) ----
$typeRows = New-Object System.Collections.Generic.List[object]
$typeCount = $result.EventTypes.Length
for ($i = 0; $i -lt $typeCount; $i++) {
    $typeValue = [uint32]$result.EventTypes[$i]
    $typeName = [string]$result.EventTypeNames[$i]
    $count = [long]$result.ByType[$i]
    $idObj0 = [long]$result.ByTypeIdObjectZero[$i]
    $pct = 0.0
    if ($total -gt 0) { $pct = $count / $total * 100.0 }
    $perS = $count / $durationS
    $typeRows.Add([ordered]@{
        hex           = ('0x{0:X4}' -f $typeValue)
        name          = $typeName
        count         = $count
        per_s         = Round3 $perS
        pct           = Round3 $pct
        idobject0     = $idObj0
        idobject0_per_s = Round3 ($idObj0 / $durationS)
    })
}

# ---- main summary ----
$idObjZero = [long]$result.IdObjectZero
$idObjNonZero = [long]$result.IdObjectNonZero
$check = [long]$result.CheckEvents
$locChange = [long]$result.LocationChangeEvents
$locChangeZero = [long]$result.LocationChangeIdObjectZero
$typeSum = 0L
for ($i = 0; $i -lt $typeCount; $i++) { $typeSum += [long]$result.ByType[$i] }
$typeSumOk = ($typeSum + [long]$result.UnknownEvents) -eq $total
$idObjectSumOk = ($idObjZero + $idObjNonZero) -eq $total
$checkPartitionOk = ($check + $locChangeZero + $idObjNonZero) -eq $total

$idObjZeroPct = 0.0
if ($total -gt 0) { $idObjZeroPct = $idObjZero / $total * 100.0 }
$idObjNonZeroPct = 0.0
if ($total -gt 0) { $idObjNonZeroPct = $idObjNonZero / $total * 100.0 }
$checkPctOfTotal = 0.0
if ($total -gt 0) { $checkPctOfTotal = $check / $total * 100.0 }
$checkPctOfIdObjZero = 0.0
if ($idObjZero -gt 0) { $checkPctOfIdObjZero = $check / $idObjZero * 100.0 }
$locChangePct = 0.0
if ($total -gt 0) { $locChangePct = $locChange / $total * 100.0 }
$noCheckCount = $total - $check
$noCheckPct = 0.0
if ($total -gt 0) { $noCheckPct = $noCheckCount / $total * 100.0 }

# ---- probe self cost (GROSS first: the pump itself must be ~free) ----
$selfCpuS = [double]$result.SelfCpuMeasureS
$controlCpuS = [double]$result.SelfCpuControlS
$controlDurS = [double]$result.ControlDurationS
$probeCpuPct = $selfCpuS / $durationS * 100.0
$controlCpuPerS = 0.0
$controlCpuPct = 0.0
if ($controlDurS -gt 0.0) {
    $controlCpuPerS = $controlCpuS / $controlDurS
    $controlCpuPct = $controlCpuPerS * 100.0
}
$expectedControlCpuS = $controlCpuPerS * $durationS
$netCpuS = $selfCpuS - $expectedControlCpuS
if ($netCpuS -lt 0.0) { $netCpuS = 0.0 }
$probeNetCpuPct = $netCpuS / $durationS * 100.0
$usPerEventIncl = $null
$usPerEventNet = $null
if ($total -gt 0) {
    $usPerEventIncl = $selfCpuS * 1000000.0 / $total
    $usPerEventNet = $netCpuS * 1000000.0 / $total
}
$overheadTargetPct = 0.5
$overheadGrossOk = $probeCpuPct -lt $overheadTargetPct
$overheadControlOk = $controlCpuPct -lt $overheadTargetPct
$overheadOk = $overheadGrossOk -and $overheadControlOk
$callbackUsPerCall = $null
if ($callbackNsPerCall -ne $null) { $callbackUsPerCall = [double]$callbackNsPerCall / 1000.0 }
# When GetProcessTimes reads 0 over the whole window, the true delivery cost is
# below the 100 ns timer resolution: the per-event gross cost is not measurable.
$deliveryBelowResolution = ($selfCpuS -le 0.0)

# ---- series-derived stats ----
$rateRows = @($series | Where-Object { [double]$_.WindowS -ge (0.5 * $intervalSeconds) })
$eventRates = @()
foreach ($row in $rateRows) { $eventRates += [double]$row.EventsDelta / [double]$row.WindowS }
$checkRates = @()
foreach ($row in $rateRows) { $checkRates += [double]$row.CheckDelta / [double]$row.WindowS }
$eventRateAvg = $eventsPerS
$eventRateMedian = Get-Median ([double[]]$eventRates)
$eventRateMax = $null
if ($eventRates.Count -gt 0) { $eventRateMax = ($eventRates | Measure-Object -Maximum).Maximum }

$samplerCpuPcts = @()
$samplerCpuMsTotal = [double]$result.SamplerCpuMeasureS
$samplerValid = [bool]$result.SamplerPresent -and [bool]$result.SamplerTimesOk
if ($samplerValid) {
    foreach ($row in $series) {
        if ([bool]$row.SamplerValid) { $samplerCpuPcts += [double]$row.SamplerCpuPctCore }
    }
}
$samplerSummary = $null
$correlation = $null
if ($samplerValid) {
    $samplerCpuAvgFromSeries = $null
    $samplerCpuAvgFromTotal = $samplerCpuMsTotal / 1000.0 / $durationS * 100.0
    if ($samplerCpuPcts.Count -gt 0) {
        $samplerCpuAvgFromSeries = ($samplerCpuPcts | Measure-Object -Average).Average
    }
    $samplerCpuMin = $null
    $samplerCpuMax = $null
    if ($samplerCpuPcts.Count -gt 0) {
        $samplerCpuMin = ($samplerCpuPcts | Measure-Object -Minimum).Minimum
        $samplerCpuMax = ($samplerCpuPcts | Measure-Object -Maximum).Maximum
    }
    $samplerSummary = [ordered]@{
        pid                   = [int]$result.SamplerPid
        process_name          = $samplerProcName
        process_start_local   = if ($samplerProcStartTime -ne $null) { $samplerProcStartTime.ToString('yyyy-MM-dd HH:mm:ss') } else { $null }
        cpu_total_s           = Round6 $samplerCpuMsTotal
        cpu_avg_pct_core      = if ($samplerCpuAvgFromSeries -ne $null) { Round3 $samplerCpuAvgFromSeries } else { Round3 $samplerCpuAvgFromTotal }
        cpu_avg_pct_core_from_total = Round3 $samplerCpuAvgFromTotal
        cpu_median_pct_core   = if ($samplerCpuPcts.Count -gt 0) { Round3 (Get-Median ([double[]]$samplerCpuPcts)) } else { $null }
        cpu_min_pct_core      = if ($samplerCpuMin -ne $null) { Round3 $samplerCpuMin } else { $null }
        cpu_max_pct_core      = if ($samplerCpuMax -ne $null) { Round3 $samplerCpuMax } else { $null }
    }

    # Pearson correlations: same-interval and next-interval (CPU may trail events).
    $pairX = @()
    $pairY = @()
    $lagX = @()
    $lagY = @()
    for ($i = 0; $i -lt $series.Count; $i++) {
        if (-not [bool]$series[$i].SamplerValid) { continue }
        if ([double]$series[$i].WindowS -lt (0.5 * $intervalSeconds)) { continue }
        $rate = [double]$series[$i].EventsDelta / [double]$series[$i].WindowS
        $checkRate = [double]$series[$i].CheckDelta / [double]$series[$i].WindowS
        $pairX += $rate
        $pairY += [double]$series[$i].SamplerCpuPctCore
        if (($i + 1) -lt $series.Count -and [bool]$series[$i + 1].SamplerValid) {
            $lagX += $rate
            $lagY += [double]$series[$i + 1].SamplerCpuPctCore
        }
    }
    $correlation = [ordered]@{
        r_event_rate_vs_sampler_cpu        = Get-Pearson ([double[]]$pairX) ([double[]]$pairY)
        r_event_rate_vs_sampler_cpu_lag1   = Get-Pearson ([double[]]$lagX) ([double[]]$lagY)
        intervals_used                     = $pairX.Count
    }
}

