<#
    EventProbe.ps1 - Passive WinEvent counter + CPU correlation probe for the
    RiotSwitch performance campaign.

    WHAT IT DOES
      Installs the same two SetWinEventHook registrations as the hidden watcher
      (src/RiotSwitcher.App/RiotWindowTracker.cs):
        hook 1: EVENT_OBJECT_CREATE 0x8000 .. EVENT_OBJECT_LOCATIONCHANGE 0x800B
        hook 2: EVENT_SYSTEM_FOREGROUND 0x0003
        flags : WINEVENT_OUTOFCONTEXT | WINEVENT_SKIPOWNPROCESS, global (process=0, thread=0)
      A managed out-of-context callback counts every delivered event without
      calling Check/Find/BeginInvoke, then stops and reports:
        - total events and events/s,
        - per event type counts and rates,
        - idObject == 0 vs idObject != 0,
        - events that WOULD trigger Check() in the app (type != LOCATIONCHANGE
          and idObject == 0),
        - a time series (one row per -IntervalMs) with the probe's own CPU and,
          with -SamplerPid, the CPU of the sampled process on the same timeline.

    SELF COST
      The probe measures its own process CPU (GetProcessTimes, kernel+user) over
      the measurement window and over a control window without hooks. The
      blocking pump (MsgWaitForMultipleObjectsEx + full message drain) must cost
      ~0 % of a core: the proxy reports the GROSS percentage of one core and
      fails overhead_ok when either the control window or the measurement window
      reaches 0.5 %. The net value (gross - control pro rata) is informational.
      A separate micro-benchmark times the managed counting callback itself
      (ns/call): it is a LOWER BOUND of the app hook cost (the app additionally
      runs BeginInvoke(Check) -> RiotClientWindow.Find() per triggering event).

    SELF TEST (positive control)
      _EventGen.ps1 creates an OFF-SCREEN WinForms window in another process,
      moves it, hides/shows it, closes it, and periodically emits synthetic
      events through NotifyWinEvent() with a non-zero idObject (OBJID_CARET,
      OBJID_CURSOR, OBJID_CLIENT) so that both idObject partitions are proven
      to be counted. Run it in parallel with a probe run to prove that events
      are actually delivered and counted:
        Start-Process powershell -ArgumentList '-NoProfile','-File','_EventGen.ps1' -WindowStyle Hidden
        .\EventProbe.ps1 -DurationSeconds 60 -Csv results\selftest.csv -Json results\selftest.json
      Expected: total > 0, LOCATIONCHANGE and SHOW/HIDE present, both idObject
      partitions > 0, consistency OK. Use >= 60 s: process CPU accounting is
      refreshed once per clock tick (~15.6 ms), so a short run cannot resolve
      the probe's own cost reliably.

    PASSIVE
      Read-only: it installs its own hooks and reads process CPU times with query
      access only. It never sends input, never moves/shows/hides a window and
      never touches the sampled process. No rebuild, no dist/ changes.

    USAGE
      # 60 s passive run in front of the running watcher, with CPU correlation:
      .\EventProbe.ps1 -DurationSeconds 60 -SamplerPid 30124 -Label baseline `
          -Csv results\events-baseline.csv -Json results\events-baseline.json

      # Event-rate only (no external process):
      .\EventProbe.ps1 -DurationSeconds 60 -Csv results\events.csv -Json results\events.json

      # Mirror the app more closely by ignoring events generated by the watcher
      # process itself (the app skips its own process through SKIPOWNPROCESS):
      .\EventProbe.ps1 -DurationSeconds 60 -SamplerPid 30124 -ExcludePid 30124 ...

    PARAMETERS
      -DurationSeconds  measurement window (hooks installed), default 60.
      -IntervalMs       series period, default 1000.
      -ControlSeconds   baseline window without hooks, default 3 (subtracted).
      -WarmupSeconds    warmup window with hooks, counters reset afterwards, default 1.
      -SamplerPid       optional external process id to sample (read-only CPU times).
      -SamplerName      alternative to -SamplerPid: pick the newest process by name
                        (e.g. RiotSwitch).
      -ExcludePid       optional list of process ids whose events must not be
                        counted (e.g. the watcher itself, to approximate what the
                        app sees with WINEVENT_SKIPOWNPROCESS). Events generated by
                        a window-less source cannot be attributed and are counted.
      -Label            free-form label stored in CSV/JSON, default 'probe'.
      -Csv / -Json      optional output paths (ASCII, one CSV row per interval).

    OUTPUT
      Human summary on stdout, then a SUMMARY_JSON block (summary only, no
      series), then the paths of the written files. Exit code 0 on success,
      2 when the hooks cannot be installed, 1 on other errors.

    PowerShell 5.1 / .NET Framework 4.x compatible. ASCII-only source on purpose.
#>
