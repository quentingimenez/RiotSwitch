function Round2([double]$Value) { return [Math]::Round($Value, 2) }
function Round3([double]$Value) { return [Math]::Round($Value, 3) }
function Round6([double]$Value) { return [Math]::Round($Value, 6) }

function Get-Median([double[]]$Values) {
    if ($Values -eq $null -or $Values.Count -eq 0) { return $null }
    $sorted = @($Values | Sort-Object)
    $mid = [int][Math]::Floor($sorted.Count / 2)
    if ($sorted.Count % 2 -eq 1) { return $sorted[$mid] }
    return ($sorted[$mid - 1] + $sorted[$mid]) / 2.0
}

function Get-Pearson([double[]]$X, [double[]]$Y) {
    if ($X -eq $null -or $Y -eq $null) { return $null }
    if ($X.Count -lt 2 -or $Y.Count -ne $X.Count) { return $null }
    $mx = 0.0
    $my = 0.0
    for ($i = 0; $i -lt $X.Count; $i++) { $mx += $X[$i]; $my += $Y[$i] }
    $mx = $mx / $X.Count
    $my = $my / $Y.Count
    $sxy = 0.0
    $sxx = 0.0
    $syy = 0.0
    for ($i = 0; $i -lt $X.Count; $i++) {
        $dx = $X[$i] - $mx
        $dy = $Y[$i] - $my
        $sxy += $dx * $dy
        $sxx += $dx * $dx
        $syy += $dy * $dy
    }
    if ($sxx -le 0.0 -or $syy -le 0.0) { return $null }
    return $sxy / [Math]::Sqrt($sxx * $syy)
}

# ---- resolve optional external sampler process ----
$samplerProcName = $null
$samplerProcStartTime = $null
if ($SamplerPid -le 0 -and $SamplerName -ne '') {
    $candidate = Get-Process -Name $SamplerName -ErrorAction SilentlyContinue |
        Sort-Object StartTime -Descending |
        Select-Object -First 1
    if ($candidate -ne $null) { $SamplerPid = $candidate.Id }
}
if ($SamplerPid -gt 0) {
    $samplerProc = Get-Process -Id $SamplerPid -ErrorAction SilentlyContinue
    if ($samplerProc -eq $null) {
        Write-Warning "SamplerPid $SamplerPid not found; running without CPU sampler."
        $SamplerPid = 0
    }
    else {
        $samplerProcName = $samplerProc.ProcessName
        $samplerProcStartTime = $samplerProc.StartTime
    }
}

# ---- run the native probe ----
$options = New-Object RiotSwitchPerf.Probe.ProbeOptions
$options.DurationMs = [int][Math]::Round($DurationSeconds * 1000.0)
$options.IntervalMs = [int]$IntervalMs
$options.ControlMs = [int][Math]::Round($ControlSeconds * 1000.0)
